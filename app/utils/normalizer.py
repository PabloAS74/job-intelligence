def normalize_role(raw_title: str) -> str:
    """
    Normaliza el título del rol a un rol estándar basado en el diccionario ROLE_MAPPING.
    Si no se encuentra una coincidencia, devuelve "Other".

    Args:
        raw_title (str): Título del rol sin normalizar.

    Returns:
        str: Rol normalizado.
    """
    raw_title_lower = raw_title.lower()
    
    for normalized_role, keywords in ROLE_MAPPING.items():
        for keyword in keywords:
            if keyword in raw_title_lower:
                return normalized_role
    
    return "Other"